        "脸红" to "音量收小一点、语速偏快，字与字之间有点含糊发慌，像在掩饰什么。",
        "生气" to "语速加快、音量抬高、气息往外冲，尾音往上顶。",
        "晕" to "语速拖慢、语气发飘，句尾明显没力气。",
        "＞＜" to "语速又快又碎、音量偏高，带着抗拒和快撑不住的感觉。",
        "0.0" to "语速慢、音量平，几乎没有情绪起伏，冷淡敷衍。",
        "星星眼" to "语速偏快、音调上扬，藏不住的兴奋。",
        "流泪" to "气息不稳、声音发颤带一点鼻音，委屈。",
        "月卡" to "音调上扬、语速轻快，得意洋洋。",
        "抱胸" to "语速稳、音量沉下来，带着看戏的从容。",
        "捧心" to "声音放软、语速放慢，甜而黏。",
        "要饭" to "拖长音、音量放低，可怜巴巴地讨好。",
        "外套" to "语速利落、音量提起来，摆酷的自信。",

        // ---------------- DeepSeek 酱 ----------------
        "晕晕" to "语速拖慢、语气发飘，句尾明显没力气。",
        "爱心眼" to "声音放软、语速放慢，甜得有点冒泡。",
        "哭" to "气息不稳、声音发颤带一点鼻音，委屈。",
        "开心兴奋" to "语速快、音调高，笑得有点收不住。",
        "调皮" to "语速轻快、尾音上扬，带着坏笑。",
        "流汗" to "语速发虚、音量偏小，有点心虚地拖着说。",
        "问号" to "语调上扬，带着明显的疑惑和停顿。",
        "吐魂" to "有气无力、语速极慢、音量很小，像快断气了。",
        "呆呆眼" to "语速慢、语调平，像在走神。",
        "闭眼口水" to "语速拖沓、语气黏糊，馋得不行。",
        "阴暗" to "音量很低、语速慢、语气发闷，没有起伏。",
        "蛋包饭" to "语气一下振奋起来、语速变快，透着满足。",
        "鲸鱼" to "声音放软、语速放慢，卖萌。",
        "猫猫贴纸" to "语速轻快、音调偏高，撒娇卖萌。",
        "双手比耶" to "语速快、音调高，得意。",
        "墨镜" to "语速稳、音量沉，故意装镇定。"
    )

    /**
     * 查这一轮的语气修饰。
     *
     * @param key [Live2DExpression.key]；null（本轮没有表情标签）返回 null
     * @return null 表示**不改语气**，沿用角色原本的 `ttsPrompt` ——
     *         这既覆盖"情绪不明显所以没加标签"的正常情况，也覆盖表里漏了这个键的情况
     */
    fun styleFor(key: String?): String? = key?.let { STYLES[it.trim()] }

    /** 这张表里配了语气的键（供日志/排查用，例如确认某个键到底有没有配） */
    fun knownKeys(): Set<String> = STYLES.keys

    /**
     * 把角色的基础风格与本轮的情绪语气拼成**这一次**要下发的 TTS 风格提示词。
     *
     * 两段的分工必须写清楚，否则模型会把它们当成同一层级的两句话、随便挑一句执行：
     * - 基础段（[base]）描述**音色与基本语速**，是整个角色一贯的说话方式，不要它变；
     * - 情绪段（[style]）只描述**这一句**的临时偏离。
     *
     * 基础段为空（角色没配风格）时直接用情绪段；情绪段为 null 时原样返回基础段。
     */
    fun composePrompt(base: String, style: String?): String {
        val cleanBase = base.trim()
        val cleanStyle = style?.trim().orEmpty()
        return when {
            cleanStyle.isEmpty() -> cleanBase
            cleanBase.isEmpty() -> cleanStyle
            else -> "$cleanBase\n" +
                "上面是你一贯的说话方式；这一句请额外这样处理：$cleanStyle" +
                "（音色与基本语速不变，只调整这一句的情绪和节奏）"
        }
    }
}
