package com.lv999call.app.domain.model

/**
 * 「这一轮的情绪 → 这一句该怎么念」的语气表。
 *
 * ## 为什么需要它
 *
 * LLM 用 `[[e:生气]]` 这样的标签表达情绪，但那条标签此前**只驱动 Live2D 表情**，
 * 声音一个字都不变 —— 一个角色从头到尾只有一份静态 `ttsPrompt`。于是"笑着说出很凶的话"
 * 这种割裂一直存在：声音是通话的主要载体，表情变了而语气不变，等于表演只做了一半。
 *
 * 这件事能做成的前提是**时序**：TTS 不是在 LLM 流式过程中边收边合成的，而是等整段文本
 * 收完之后才发起（见 [com.lv999call.app.domain.usecase.ProcessAudioUseCase] 的 Step 3）。
 * 也就是说这一轮的表情标签**在开嗓之前就已经拿到了**，可以拿它去改这一轮的语气。
 *
 * ## 为什么是「按 key 的全局表」而不是给 [Live2DExpression] 加一个字段
 *
 * 1. 语气是**表演**参数。调它的时候要能一眼看全：整张表读下来就是"她的情绪音域"，
 *    而分散到两份注册表的三十多个条目里就没法整体调了。
 * 2. 多个角色**共用同一批情绪键**（`脸红` / `生气` / `星星眼` 在两个角色里都有），
 *    放进各自的注册表就要各写一遍、改一处漏一处 —— 而它们本来就该念得一样。
 * 3. 代价是键名写错会**静默失效**（查不到就退回角色原本的语气，不报错）。所以
 *    [com.lv999call.app.domain.usecase.ProcessAudioUseCase] 在本轮出现了表情、
 *    却查不到对应语气时会打一条日志 —— 真机跑一轮就能看出表里漏了哪个键。
 *
 * ## 写法约定（语域对齐 [BuiltInCharacter.defaultTtsPrompt]）
 *
 * 这些字符串是**给 TTS 模型的自然语言指令**（会被放进 TTS 请求的 user 消息里，
 * 见 `ChatRepository.synthesizeSpeech`），所以要写成"怎么发声"而不是"什么情绪"：
 * 说清 **语速 / 音量 / 音高 / 气息 / 节奏**。只写"生气"没用 —— 那是给 Live2D 看的
 * [Live2DExpression.hint]，TTS 模型读了不知道该把嗓子往哪儿调。
 *
 * ## 不做什么
 *
 * 不做"情绪强度分级"（`生气` 轻 / 重两档）。标签协议本身规定**每次最多 1 个**，
 * 加档位就得改协议与两个角色的提示词，而收益只是"同一情绪两档语气"，
 * 不值这个扩散面。真要更细，先看这张表够不够用。
 *
 * ## 已知耦合：关掉 Live2D 就听不到情绪
 *
 * 表情标签协议**只在 `live2dEnabled` 打开时注入**（见 `ProcessAudioUseCase` 拼
 * `effectivePrompt` 那一处）。所以关掉 Live2D 之后，LLM 根本不会输出 `[[e:…]]`，
 * 这张表也就无从生效 —— 语气会一直停在角色的基础风格上。
 *
 * 这是**刻意不修**的：标签协议的全部文案都是围着"驱动虚拟形象"写的，为一个
 * "只要声音不要形象"的场景再注入一整块协议，收益远小于扩散面。Live2D 默认是开的，
 * 所以只有主动关掉它的用户会遇到这个边界。
 */
object EmotionVoiceStyles {

    /**
     * 键 = [Live2DExpression.key]（两个角色的键合在一张表里，同名即同语气）。
     *
     * 顺序按角色注册表的顺序排，方便与 [Live2DExpressions] 逐条对照。
     */
    private val STYLES: Map<String, String> = mapOf(
        // ---------------- 银狼 ----------------
